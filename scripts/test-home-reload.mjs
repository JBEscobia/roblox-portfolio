import {chromium,expect} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch();
const base=process.env.TEST_URL||'http://127.0.0.1:4321';
const page=await browser.newPage({viewport:{width:1440,height:900}});
await page.goto(base+'/#projects',{waitUntil:'networkidle'});
await expect.poll(()=>page.evaluate(()=>scrollY)).toBeGreaterThan(0);
await page.locator('#site-nav a').filter({hasText:'Projects'}).click();
await expect.poll(()=>new URL(page.url()).hash).toBe('#projects');
await page.waitForTimeout(1000);
console.log('Before reload',await page.evaluate(()=>({url:location.href,y:scrollY})));
await page.reload({waitUntil:'networkidle'});await page.waitForTimeout(1000);
const result=await page.evaluate(()=>({url:location.href,y:scrollY,phase:document.querySelector('.descent').dataset.animationState,restoration:history.scrollRestoration}));
console.log('After reload',result);
assert.equal(result.y,0,'Reload must begin at the top even after a project anchor was clicked');
assert.equal(new URL(result.url).hash,'','Reload should discard the previous homepage section anchor');
assert.equal(result.phase,'idle','The intro must wait for a fresh gesture');
await page.mouse.wheel(0,260);await expect(page.locator('.descent')).toHaveAttribute('data-animation-state','playing');assert.equal(await page.evaluate(()=>scrollY),0);
await expect(page.locator('.descent')).toHaveAttribute('data-animation-state','complete',{timeout:8000});assert.equal(await page.evaluate(()=>scrollY),0);
await page.locator('#site-nav a').filter({hasText:'Projects'}).click();await expect.poll(()=>page.evaluate(()=>scrollY)).toBeGreaterThan(0);
await page.reload({waitUntil:'networkidle'});await expect.poll(()=>page.evaluate(()=>scrollY)).toBe(0);assert.equal(new URL(page.url()).hash,'');
console.log('PASS: fresh deep link and clicked navigation work; repeated reloads start at top; intro waits for input without moving the page.');
await browser.close();
